let currentLang = localStorage.getItem("kefu-lang") || "zh";

function t(key) {
  return (I18N[currentLang] || I18N.zh)[key] || I18N.zh[key] || key;
}

function getPrompts() {
  return (I18N[currentLang] || I18N.zh).prompts || I18N.zh.prompts;
}

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("kefu-lang", lang);
  document.documentElement.lang = lang === "ar" ? "ar" : lang === "en" ? "en" : "zh-CN";
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", lang === "ar");

  const titleEl = document.querySelector(".brand-title") || document.querySelector("#brandTitle");
  if (titleEl) {
    if (lang === "en") {
      titleEl.innerHTML = `<span class="type-ink">Jia</span><span class="type-pink">ozi</span>`;
    } else if (lang === "ar") {
      titleEl.innerHTML = `<span class="type-pink">جياوزي</span>`;
    } else {
      titleEl.innerHTML = `<span class="type-ink">饺</span><span class="type-pink">子</span>`;
    }
  }
  const brandTag = document.querySelector(".brand-tag");
  if (brandTag) {
    const tag =
      lang === "en" ? "Dedicated agent" : lang === "ar" ? "وكيلك الخاص" : "专属客服";
    brandTag.innerHTML = `<span class="type-mark">${tag}</span>`;
  }
  const chatHeading = document.querySelector(".chat-heading") || document.querySelector("#chatHeading");
  if (chatHeading) {
    if (lang === "en") {
      chatHeading.innerHTML = `<span class="type-ink">Just </span><span class="type-pink">say it</span>`;
    } else if (lang === "ar") {
      chatHeading.innerHTML = `<span class="type-pink">قل ما تحتاج</span>`;
    } else {
      chatHeading.innerHTML = `<span class="type-ink">有事</span><span class="type-pink">直说</span>`;
    }
  }
  const welcomeBrand = document.querySelector(".welcome-brand") || document.querySelector("#welcomeBrand");
  if (welcomeBrand) {
    if (lang === "en") {
      welcomeBrand.innerHTML = `<span class="type-ink">Jia</span><span class="type-pink">ozi</span>`;
    } else if (lang === "ar") {
      welcomeBrand.innerHTML = `<span class="type-pink">جياوزي</span>`;
    } else {
      welcomeBrand.innerHTML = `<span class="type-ink">饺</span><span class="type-pink">子</span>`;
    }
  }
  const welcomeLead = document.querySelector(".welcome-lead");
  if (welcomeLead) {
    if (lang === "en") {
      welcomeLead.innerHTML = `
        <span class="type-lead-a">Orders</span>
        <span class="type-dot">·</span>
        <span class="type-lead-b">Tracking</span>
        <span class="type-dot">·</span>
        <span class="type-lead-c">Returns</span>
        <br />
        <span class="type-lead-tail">Dump it on Jiaozi.</span>`;
    } else if (lang === "ar") {
      welcomeLead.innerHTML = `<span class="type-lead-tail">${I18N.ar.welcomeLead || ""}</span>`;
    } else {
      welcomeLead.innerHTML = `
        <span class="type-lead-a">查订单</span>
        <span class="type-dot">·</span>
        <span class="type-lead-b">追物流</span>
        <span class="type-dot">·</span>
        <span class="type-lead-c">办退换</span>
        <br />
        <span class="type-lead-tail">丢给饺子就行。</span>`;
    }
  }
  const welcomeAgent = document.querySelector(".welcome-agent");
  if (welcomeAgent) {
    const agentText =
      lang === "en"
        ? "Your dedicated agent — Jiaozi"
        : lang === "ar"
          ? "وكيلك الخاص — جياوزي"
          : "您的专属客服——饺子";
    welcomeAgent.innerHTML = `<span class="type-chip type-chip-soft">${agentText}</span>`;
  }
  const importBtn = document.getElementById("importOrdersBtn");
  if (importBtn && I18N[currentLang]?.importOrders) {
    importBtn.textContent = I18N[currentLang].importOrders;
  }
  const newBtn = document.getElementById("newSession");
  if (newBtn) newBtn.textContent = t("newSession");
  const sendBtn = document.getElementById("send");
  if (sendBtn) sendBtn.textContent = t("send");
  const cancelBtn = document.getElementById("cancel");
  if (cancelBtn) cancelBtn.textContent = t("cancel");
  const input = document.getElementById("input");
  if (input) input.placeholder = t("placeholder");
  const loginBtn = document.getElementById("loginBtn");
  if (loginBtn) loginBtn.textContent = t("login");
  const logoutBtn = document.getElementById("logoutBtn");
  if (logoutBtn) logoutBtn.textContent = t("logout");
  const loginEmail = document.getElementById("loginEmail");
  if (loginEmail) loginEmail.placeholder = t("loginPlaceholder");
  const historyTitle = document.querySelector(".session-list-wrap .sidebar-subtitle");
  if (historyTitle) historyTitle.textContent = t("historySessions");
  const ordersTitle = document.getElementById("ordersTitle");
  if (ordersTitle) ordersTitle.textContent = t("myOrders");
  const adminLink = document.querySelector(".admin-link");
  if (adminLink) adminLink.title = t("adminLink");
  if (typeof renderSessionList === "function") renderSessionList();
  if (typeof renderQuickPrompts === "function") renderQuickPrompts();
  if (typeof renderSceneButtons === "function") renderSceneButtons();
  if (typeof updateConnStatus === "function") updateConnStatus();
  const handoffBtn = document.getElementById("handoffBtn");
  if (handoffBtn && !handoffBtn.dataset.busy) handoffBtn.textContent = t("handoff");
  const banner = document.getElementById("degradedBanner");
  if (banner && !banner.hidden) banner.textContent = t("redisDegraded");

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
}

function initLanguageSwitcher() {
  const sidebar = document.querySelector(".sidebar");
  if (!sidebar || document.getElementById("langSwitcher")) return;

  const wrap = document.createElement("div");
  wrap.id = "langSwitcher";
  wrap.className = "lang-switcher";
  wrap.innerHTML = `
    <button type="button" class="lang-btn" data-lang="zh">中文</button>
    <button type="button" class="lang-btn" data-lang="en">EN</button>
    <button type="button" class="lang-btn" data-lang="ar">عربي</button>
  `;
  const newSession = sidebar.querySelector("#newSession");
  if (newSession) sidebar.insertBefore(wrap, newSession);

  wrap.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
  });

  applyLanguage(currentLang);
}
